# One row per (company, breach): the breached domain equals, or is a subdomain of, a current company
# domain. in_latest_catalogue is false for a breach HIBP has since removed (kept for history).
COMPANY_VIEW = """
CREATE VIEW company_public_breaches AS
WITH latest AS (SELECT max(last_seen_run_id) AS run_id FROM public_breach_metadata)
SELECT DISTINCT ON (cd.company_id, b.id)
       cd.company_id, d.id AS domain_id, d.name AS company_domain,
       CASE WHEN b.domain = d.name THEN 'same_domain' ELSE 'subdomain' END AS match_basis,
       b.id AS breach_id, b.name AS breach_name, b.title, b.domain AS breached_domain, b.breach_date,
       b.added_at, b.pwn_count, b.data_classes,
       (b.data_classes ? 'Passwords') AS passwords_exposed,
       b.is_verified, b.is_fabricated, b.is_sensitive, b.is_spam_list, b.is_malware, b.is_stealer_log,
       b.is_retired, (b.last_seen_run_id = latest.run_id) AS in_latest_catalogue,
       b.evidence_version_id
FROM public_breach_metadata b
CROSS JOIN latest
JOIN domains d ON b.domain = d.name OR b.domain LIKE '%.' || d.name
JOIN company_domains cd ON cd.domain_id = d.id AND (cd.valid_to IS NULL OR cd.valid_to > current_date)
ORDER BY cd.company_id, b.id, (b.domain = d.name) DESC, length(d.name) DESC
"""


